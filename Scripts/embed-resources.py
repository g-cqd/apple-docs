#!/usr/bin/env python3
"""Generate Swift sources embedding each target's `Resources/` files, so `apple-docs` is one self-contained binary.

SwiftPM resource bundles (`Bundle.module`) must ship beside the executable; a binary copied anywhere else (archives,
package managers, containers) then crashes on first use. Instead, every file listed in RESOURCES below is compiled
into its target as a raw string literal in `<Target>/Embedded<Name>.swift`; the `Resources/` files stay the editable
source of truth. `AppleDocsQualityTests` fails when a generated file is out of date.

Usage: Scripts/embed-resources.py [--check]
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# (target, resource path relative to the target, Swift type name, doc summary)
RESOURCES = [
    ("AppleDocsStorage", "Resources/schema-v1-corpus.sql", "EmbeddedCorpusSchema",
     "Schema v1 DDL: corpus, relationship, vector, and search tables (`schema-v1-corpus.sql`)."),
    ("AppleDocsStorage", "Resources/schema-v1-assets.sql", "EmbeddedAssetSchema",
     "Schema v1 DDL: fonts, SF Symbols, and sync state tables (`schema-v1-assets.sql`)."),
    ("AppleDocsMCP", "Resources/mcp-tools.json", "EmbeddedMCPTools",
     "MCP tool descriptors served by `tools/list` (`mcp-tools.json`)."),
    ("AppleDocsSources", "Resources/sources.json", "EmbeddedSourceRegistry",
     "Documentation source definitions (`sources.json`)."),
    ("AppleDocsWeb", "Resources/style.css", "EmbeddedStylesheet", "The web UI stylesheet (`style.css`)."),
    ("AppleDocsWeb", "Resources/app.js", "EmbeddedScript", "The web UI script (`app.js`)."),
]


def render(type_name: str, summary: str, content: str) -> str:
    delimiter = "#"
    while f'"""{delimiter}' in content:
        delimiter += "#"
    # swift-format's layout: content and closing delimiter indented 8 spaces (stripped by Swift at compile time, so
    # the value is the file verbatim); blank lines stay empty.
    # Swift drops the newline right before the closing delimiter, so a file ending in "\n" keeps an empty last line.
    lines = content.split("\n")
    body = "".join(("        " + line if line else "") + "\n" for line in lines)
    return (
        "// Generated by Scripts/embed-resources.py from the target's Resources/ — do not edit.\n"
        "// swiftlint:disable line_length\n\n"
        f"/// {summary}\n"
        f"enum {type_name} {{\n"
        f"    static let text = {delimiter}\"\"\"\n"
        f"{body}"
        f"        \"\"\"{delimiter}\n"
        "}\n"
    )


def generated() -> dict:
    out = {}
    for target, relative, type_name, summary in RESOURCES:
        source = ROOT / "Sources" / target / relative
        out[ROOT / "Sources" / target / f"{type_name}.swift"] = render(type_name, summary, source.read_text("utf-8"))
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in generated().items():
        current = path.read_text("utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.write_text(text, "utf-8")
    if check and stale:
        print("out of date (run Scripts/embed-resources.py):", *stale, sep="\n  ")
        return 1
    print("embedded resources up to date" if not stale else f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
